def lines(text, width, size=1000):
    # 칸 높이 어림(hwpx_fillseg 와 같은 글자 폭)
    w = 0
    for c in text:
        o = ord(c)
        w += size * (1.0 if 0xAC00 <= o <= 0xD7A3 else 0.56 if c == " " else 0.52 if c.isascii() else 0.62)
    return max(1, -(-int(w) // max(1, width)))


