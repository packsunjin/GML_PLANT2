def table(rows, widths):
    """옛 표12(405)를 본보기로 3열 표를 만든다. rows[0] 은 머리글."""
    tpl = re.search(r'<hp:p id="405".*?</hp:tbl>.*?</hp:p>', s, re.S).group(0)
    trs = re.findall(r"<hp:tr>.*?</hp:tr>", tpl, re.S)
    head_tr, body_tr = trs[0], trs[1]
    out_rows, total = [], 0
    for r, cells in enumerate(rows):
        tr = head_tr if r == 0 else body_tr
        tcs = re.findall(r"<hp:tc .*?</hp:tc>", tr, re.S)
        h = max(lines(t, widths[c] - 1020) for c, t in enumerate(cells)) * 1600 + 400
        h = max(h, 1800)
        total += h
        new = []
        for c, (tc, t) in enumerate(zip(tcs, cells)):
            p = re.search(r"<hp:p id=.*?</hp:p>", tc, re.S).group(0)
            p2 = with_text(re.sub(r'<hp:p id="\d+"', f'<hp:p id="{nid()}"', p, count=1), t)
            tc = tc.replace(p, p2)
            tc = re.sub(r'rowAddr="\d+"', f'rowAddr="{r}"', tc)
            tc = re.sub(r'<hp:cellSz width="\d+" height="\d+"', f'<hp:cellSz width="{widths[c]}" height="{h}"', tc)
            new.append(tc)
        out_rows.append("<hp:tr>" + "".join(new) + "</hp:tr>")
    body = tpl[:tpl.index("<hp:tr>")] + "".join(out_rows) + tpl[tpl.rindex("</hp:tr>") + len("</hp:tr>"):]
    body = re.sub(r'<hp:p id="405"', f'<hp:p id="{nid()}"', body, count=1)
    body = re.sub(r'<hp:tbl id="\d+"', f'<hp:tbl id="{TBL[0]}"', body, count=1)
    TBL[0] += 1
    body = re.sub(r'rowCnt="\d+"', f'rowCnt="{len(rows)}"', body, count=1)
    body = re.sub(r'(<hp:sz width="47620" widthRelTo="ABSOLUTE" height=")\d+', rf"\g<1>{total}", body, count=1)
    return body   # 표 문단 바깥 줄 배치는 본보기 그대로(한 줄)


