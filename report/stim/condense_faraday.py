def tops(x):
    out, depth, start = [], 0, None
    for m in re.finditer(r"<hp:p\b[^>]*?(/?)>|</hp:p>", x):
        t = m.group(0)
        if t.startswith("</"):
            depth -= 1
            if depth == 0:
                out.append((start, m.end()))
        elif m.group(1) == "/":
            if depth == 0:
                out.append((m.start(), m.end()))
        else:
            if depth == 0:
                start = m.start()
            depth += 1
    return out


def top_id(x, a):
    return re.match(r'<hp:p id="(\d+)"', x[a:]).group(1)


def leaf_re(pid):
    return re.compile(rf'<hp:p id="{pid}"[^>]*>(?:(?!<hp:p id=).)*?</hp:p>', re.S)


