def apply(root, Q):
    n = 0
    for tc in root.iter(Q("tc")):
        ts = list(tc.iter(Q("t")))
        cur = "".join(t.text or "" for t in ts)
        if cur in REW:
            ts[0].text = REW[cur]
            for t in ts[1:]: t.text = ""
            n += 1
    return n
